#!/usr/bin/env python3
"""Generate shader headers from src/render/shaders.

  shaders.py gles OUT.h      GLSL ES 3.00 source, one string per line (const char *const p3d_glsl_<name>[])
  shaders.py vk   OUT.h      SPIR-V words via glslc (const uint32_t p3d_spv_<name>[])
"""
import os, subprocess, sys, tempfile

HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'render', 'shaders')
SHADERS = [
    ('mesh_vert', 'vert', ['mesh_common.glsl', 'mesh.vert']),
    ('mesh_frag', 'frag', ['mesh_common.glsl', 'mesh.frag']),
    ('rt_vert', 'vert', ['fullscreen.vert']),
    ('rt_frag', 'frag', ['raytrace.frag']),
]

def source(files):
    return ''.join(open(os.path.join(HERE, f)).read() + '\n' for f in files)

def c_lines(text):
    # one literal per line: glShaderSource takes an array, and no literal nears C99's 4095-char limit
    out = ['    "#version 300 es\\n",']
    for line in text.splitlines():
        out.append('    "' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n",')
    return '\n'.join(out)

def main():
    mode, out = sys.argv[1], sys.argv[2]
    parts = ['/* generated by tools/shaders.py: do not edit */\n#include <stdint.h>\n']
    for name, stage, files in SHADERS:
        text = source(files)
        if mode == 'gles':
            parts.append('static const char *const p3d_glsl_%s[] = {\n%s\n};\n' % (name, c_lines(text)))
        else:
            with tempfile.TemporaryDirectory() as tmp:
                src = os.path.join(tmp, name + '.glsl')
                dst = os.path.join(tmp, name + '.inc')
                open(src, 'w').write(text)
                subprocess.run([os.environ.get('GLSLC', 'glslc'), '-std=450', '-DP3D_VK', '-O',
                                '-fshader-stage=' + stage, '-mfmt=c', src, '-o', dst], check=True)
                parts.append('static const uint32_t p3d_spv_%s[] =\n%s;\n' % (name, open(dst).read().strip()))
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    open(out, 'w').write('\n'.join(parts))

if __name__ == '__main__':
    main()
